#!/usr/bin/env python3
"""Module contract shared by the app build and setup: the runtime symbols the
game module may import (ps5/module/host-imports.txt), the ABI identity both
sides embed, and the app's import resolver."""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
IMPORTS = ROOT / 'ps5/module/host-imports.txt'
FLAGS = ROOT / 'ps5/module/compile-flags.txt'
# SDK headers the module is compiled against (paths relative to the SDK),
# recorded with build-game-module.py --write-imports.
HEADERS = ROOT / 'ps5/module/abi-headers.txt'
# Runtime implementations of kernel imports that the module overrides and then calls
# (forza::SdkImport). The module looks them up by name at run time.
LOOKUPS = ROOT / 'ps5/module/runtime-lookups.txt'
SDK = ROOT / '.deps/rexglue-sdk'
# Everything that shapes the binary interface between app and module. Runtime
# changes outside these headers keep existing modules valid.
ABI_INPUTS = [IMPORTS, FLAGS, HEADERS, LOOKUPS, ROOT / 'ps5/module/toolchain.json',
              ROOT / 'ps5/tools/prepare-static-module.py']


def abi_headers():
    return [line.strip() for line in HEADERS.read_text().splitlines()
            if line.strip() and not line.startswith('#')]


def names_in(path):
    return [line.strip() for line in path.read_text().splitlines()
            if line.strip() and not line.startswith('#')]


def imports():
    names = names_in(IMPORTS)
    if len(names) != len(set(names)) or not all(re.fullmatch(r'[A-Za-z_.$][A-Za-z_0-9.$]*', n) for n in names):
        raise ValueError('Invalid or duplicate host import')
    return names


def abi():
    digest = hashlib.sha256(b'forza-ps5-module-v1\0')
    for path in ABI_INPUTS:
        digest.update(path.read_bytes())
    for name in abi_headers():
        digest.update(name.encode() + b'\0' + (SDK / name).read_bytes())
    return digest.hexdigest()


def generate(output):
    output.mkdir(parents=True, exist_ok=True)
    (output / 'module_abi.h').write_text(f'#define FORZA_MODULE_ABI "{abi()}"\n')
    names = sorted(set(imports()) | set(names_in(LOOKUPS)))
    lines = ['// Generated by ps5/tools/module-support.py; do not edit.',
             '#include <algorithm>', '#include <cstring>', '']
    for index, name in enumerate(names):
        lines.append(f'extern "C" char forza_import_{index}[] __asm__("{name}");')
    lines += ['', 'namespace {', 'struct Entry { const char* name; void* address; };',
              'const Entry kEntries[] = {']
    for index, name in enumerate(names):
        lines.append(f'    {{"{name}", forza_import_{index}}},')
    lines += ['};', '}  // namespace', '',
              'void* forza_host_symbol(const char* name) {',
              '    const Entry* end = kEntries + sizeof(kEntries) / sizeof(kEntries[0]);',
              '    const Entry* it = std::lower_bound(kEntries, end, name, [](const Entry& e, const char* n) {',
              '        return std::strcmp(e.name, n) < 0; });',
              '    return it != end && !std::strcmp(it->name, name) ? it->address : nullptr;',
              '}', '',
              '// The module\'s forza::SdkImport (ps5/module/forza_ps5.cpp).',
              'extern "C" void* forza_runtime_symbol(const char* name) { return forza_host_symbol(name); }']
    (output / 'module_exports.cpp').write_text('\n'.join(lines) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    generate(args.output)
    print(f'Module ABI {abi()}; {len(imports())} runtime imports')


if __name__ == '__main__':
    main()
